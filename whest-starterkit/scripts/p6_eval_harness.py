"""p6_eval_harness.py

Phase 6 Evaluation Harness and Verification Wrapper.
Supports:
1. Exact metered evaluation of candidates using official `whest run`.
2. Real sampler variation via seed offset.
3. Prediction capture (8, 16, 1024) to research/phase6/predictions/{exp_id}_preds.npy.
4. Receipts saved to research/phase6/results/{exp_id}_{timestamp}.json.
5. Verification and head-to-head comparison against the frozen control.
"""

