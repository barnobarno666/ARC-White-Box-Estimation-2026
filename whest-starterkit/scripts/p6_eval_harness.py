import argparse
import datetime
import hashlib
import json
import os
import subprocess
from pathlib import Path
from typing import Any, Dict, Optional

import numpy as np

REPO_ROOT = Path(__file__).resolve().parent.parent
DATASET_PATH = r"D:\ALL CODES\AICROWD COMPETITION\datasets\mini"
P6_DIR = REPO_ROOT / "research" / "phase6"
RESULTS_DIR = P6_DIR / "results"
PREDICTIONS_DIR = P6_DIR / "predictions"
CONTROL_RECEIPT_PATH = REPO_ROOT / "research" / "phase4_next" / "results" / "P4N-00_20260906_000232.json"
CONTROL_ESTIMATOR_PATH = REPO_ROOT / "estimator.py"
EXPECTED_CONTROL_SHA = "ea8be8222b827607f65d166118500b55fcaae883b79f64b29785b46d86501ca1"


def compute_sha256(filepath: str | Path) -> str:
    h = hashlib.sha256()
    with open(filepath, "rb") as f:
        while chunk := f.read(65536):
            h.update(chunk)
    return h.hexdigest()


def generate_wrapper_script(
    real_estimator_path: Path,
    wrapper_path: Path,
    offset: int,
    preds_save_path: Path,
) -> None:
    """Generate the evaluation wrapper script."""
    wrapper_content = f'''"""Autogenerated evaluation wrapper for Phase 6."""
import dataclasses
import os
import sys
from pathlib import Path
import numpy as np

from whestbench import BaseEstimator, SetupContext
from whestbench.domain import MLP
from whestbench.loader import load_estimator_from_path

_REAL_PATH = r"{real_estimator_path.resolve()}"
_OFFSET = {offset}
_PREDS_PATH = r"{preds_save_path.resolve()}"

_real_estimator, _ = load_estimator_from_path(_REAL_PATH)
_collected_preds = []

class Estimator(BaseEstimator):
    def setup(self, ctx: SetupContext) -> None:
        _real_estimator.setup(ctx)

    def predict(self, mlp: MLP, budget: int):
        if _OFFSET != 0:
            # Inject true sampler seed offset
            new_seed = int((mlp.seed + _OFFSET) & 0xFFFFFFFF)
            mlp = dataclasses.replace(mlp, seed=new_seed)
        pred = _real_estimator.predict(mlp, budget)
        _collected_preds.append(np.asarray(pred, dtype=np.float32))
        if len(_collected_preds) == 8:
            stack = np.stack(_collected_preds, axis=0)
            Path(_PREDS_PATH).parent.mkdir(parents=True, exist_ok=True)
            np.save(_PREDS_PATH, stack)
        return pred
'''
    wrapper_path.parent.mkdir(parents=True, exist_ok=True)
    with open(wrapper_path, "w", encoding="utf-8") as f:
        f.write(wrapper_content)


def run_evaluation(
    estimator_path: str | Path,
    exp_id: str,
    n_mlps: int = 8,
    offset: int = 0,
    save_receipt: bool = True,
) -> Optional[Dict[str, Any]]:
    estimator_path = Path(estimator_path).resolve()
    if not estimator_path.exists():
        print(f"Error: Estimator file {estimator_path} not found.")
        return None

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    PREDICTIONS_DIR.mkdir(parents=True, exist_ok=True)

    cand_sha = compute_sha256(estimator_path)
    ts_str = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    preds_file = PREDICTIONS_DIR / f"{exp_id}_{ts_str}_preds.npy"
    wrapper_file = P6_DIR / f".eval_wrapper_{exp_id}.py"

    generate_wrapper_script(estimator_path, wrapper_file, offset, preds_file)

    print("\n=======================================================")
    print(f"Phase 6 Evaluation: Exp ID [{exp_id}]")
    print(f"Estimator: {estimator_path} (SHA: {cand_sha[:16]}...)")
    print(f"Panel: {n_mlps} MLPs | Sampler Offset: {offset}")
    print(f"Predictions target: {preds_file.name}")
    print("=======================================================")

    cmd = [
        "uv", "run", "whest", "run",
        "--estimator", str(wrapper_file),
        "--dataset", DATASET_PATH,
        "--split", "mini",
        "--n-mlps", str(n_mlps),
        "--runner", "local",
        "--format", "json",
    ]

    env = dict(os.environ)
    env["PYTHONUTF8"] = "1"

    start_time = datetime.datetime.now()
    proc = subprocess.run(cmd, capture_output=True, text=True, env=env, cwd=str(REPO_ROOT))
    elapsed_s = (datetime.datetime.now() - start_time).total_seconds()

    # Clean up temporary wrapper file
    if wrapper_file.exists():
        wrapper_file.unlink()

    if proc.returncode != 0:
        print(f"Execution FAILED with return code {proc.returncode}")
        print("STDERR:")
        print(proc.stderr)
        return None

    stdout = proc.stdout
    json_start = stdout.find("{")
    if json_start == -1:
        print("No JSON found in stdout:")
        print(stdout)
        return None

    try:
        raw_data = json.loads(stdout[json_start:])
    except Exception as e:
        print(f"JSON decode error: {e}")
        return None

    results = raw_data.get("results", {})
    per_mlp = results.get("per_mlp", [])

    scored_errors = []
    max_res_time = 0.0
    for m in per_mlp:
        e_m = m["final_layer_mse"]
        u_m = m.get("compute_utilization", m.get("effective_compute", 0.0) / (2**41))
        mult_m = max(0.10, u_m)
        s_m = e_m * mult_m
        m["calculated_adjusted_score"] = s_m
        scored_errors.append(s_m)
        res_t = m.get("residual_wall_time_s", 0.0)
        if res_t > max_res_time:
            max_res_time = res_t

    calc_mean_score = sum(scored_errors) / len(scored_errors) if scored_errors else 0.0
    official_score = results.get("adjusted_final_layer_score", calc_mean_score)
    raw_mse = results.get("final_layer_mse", 0.0)
    mean_util = results.get("mean_compute_utilization", 0.0)
    failures = results.get("n_failed_mlps", 0)

    # Check saved predictions
    preds_saved = preds_file.exists()
    preds_shape = None
    if preds_saved:
        preds_arr = np.load(preds_file)
        preds_shape = list(preds_arr.shape)

    print("\n[Summary Results]")
    print(f"  Adjusted Score:            {calc_mean_score:.6e} (Official: {official_score:.6e})")
    print(f"  Raw Final MSE:             {raw_mse:.6e}")
    print(f"  Mean Compute Utilization:  {mean_util * 100:.2f}% (Mult: {max(0.10, mean_util):.4f})")
    print(f"  Max Residual Wall Time:    {max_res_time:.4f}s")
    print(f"  Failures:                  {failures}")
    print(f"  Elapsed Wall Time:         {elapsed_s:.2f}s")
    print(f"  Predictions Saved:         {preds_saved} (Shape: {preds_shape})")

    # Load control data for comparison
    control_data = None
    if CONTROL_RECEIPT_PATH.exists():
        with open(CONTROL_RECEIPT_PATH, "r") as f:
            c_json = json.load(f)
            control_data = c_json.get("results", c_json)

    wins = losses = ties = 0
    max_regress_pct = -999.0
    control_score = 1.2236425135370156e-07

    if control_data and "per_mlp" in control_data:
        c_by_name = {m["mlp_name"]: m for m in control_data["per_mlp"]}
        control_score = control_data.get("calculated_adjusted_score", control_data.get("adjusted_final_layer_score", 1.2236425135370156e-07))
        rel_improvement = ((calc_mean_score - control_score) / control_score) * 100.0

        print(f"\n[Comparison vs Frozen Control ({control_score:.6e})]")
        print(f"  Relative Score Diff:       {rel_improvement:+.4f}%")
        print("\n  Per-MLP Breakdown:")
        print("  " + "-" * 75)
        print(f"  {'MLP Name':<24} | {'Candidate':<12} | {'Control':<12} | {'Diff (%)':<9} | {'W/L'}")
        print("  " + "-" * 75)

        for m in per_mlp:
            name = m["mlp_name"]
            cand_s = m["calculated_adjusted_score"]
            c_m = c_by_name.get(name)
            if c_m:
                c_s = c_m.get("calculated_adjusted_score", c_m.get("adjusted_final_layer_score", c_m["final_layer_mse"] * 0.10))
                diff_pct = ((cand_s - c_s) / c_s) * 100.0
                if diff_pct > max_regress_pct:
                    max_regress_pct = diff_pct
                if cand_s < c_s - 1e-15:
                    outcome = "WIN"
                    wins += 1
                elif cand_s > c_s + 1e-15:
                    outcome = "LOSS"
                    losses += 1
                else:
                    outcome = "TIE"
                    ties += 1
                print(f"  {name:<24} | {cand_s:.6e} | {c_s:.6e} | {diff_pct:+8.4f}% | {outcome}")
            else:
                print(f"  {name:<24} | {cand_s:.6e} | [No control match]")

        print("  " + "-" * 75)
        print(f"  Head-to-Head Record:       {wins}W - {losses}L - {ties}T")
        print(f"  Worst MLP Regression:      {max_regress_pct:+.4f}%")

    receipt = {
        "exp_id": exp_id,
        "timestamp": datetime.datetime.now().isoformat(),
        "estimator_path": str(estimator_path),
        "estimator_sha256": cand_sha,
        "offset": offset,
        "n_mlps": n_mlps,
        "calculated_adjusted_score": calc_mean_score,
        "official_adjusted_score": official_score,
        "raw_final_mse": raw_mse,
        "mean_compute_utilization": mean_util,
        "max_residual_wall_time_s": max_res_time,
        "elapsed_time_s": elapsed_s,
        "n_failed_mlps": failures,
        "predictions_saved_path": str(preds_file.relative_to(REPO_ROOT)) if preds_saved else None,
        "predictions_shape": preds_shape,
        "wins": wins,
        "losses": losses,
        "ties": ties,
        "max_regression_pct": max_regress_pct,
        "relative_improvement_pct": ((calc_mean_score - control_score) / control_score) * 100.0,
        "per_mlp": per_mlp,
    }

    if save_receipt:
        out_file = RESULTS_DIR / f"{exp_id}_{ts_str}.json"
        with open(out_file, "w") as f:
            json.dump(receipt, f, indent=2)
        print(f"\n[p6_eval_harness] Saved complete receipt to: {out_file}")

    return receipt


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Phase 6 Evaluation Harness")
    parser.add_argument("estimator", help="Path to estimator candidate")
    parser.add_argument("exp_id", help="Experiment ID (e.g. P6-00, P6-01)")
    parser.add_argument("--n-mlps", type=int, default=8, help="Number of MLPs (default: 8)")
    parser.add_argument("--offset", type=int, default=0, help="Sampler seed offset (default: 0)")
    args = parser.parse_args()

    run_evaluation(args.estimator, args.exp_id, n_mlps=args.n_mlps, offset=args.offset)
