"""p65_eval.py

Phase 6.5 Evaluation Harness and Verification Runner.
Supports:
1. Exact metered evaluation via official `whest run`.
2. Seed offset injection via wrapper without adding predict-time overhead.
3. Clean prediction capture via an atexit hook outside the measured predict() interval.
4. Paired scoring against ground truth in float64.
5. Clear distinction between RESEARCH_ONLY (diagnostic with relaxed residual gate)
   and VALIDATED (unrelaxed runner passing official 0.4s cap).
6. Atomically updates ledger.jsonl, progress.json, and appends to phase6.5report.md.
"""

from __future__ import annotations

import argparse
import datetime
import hashlib
import json
import os
import subprocess
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional

import numpy as np

REPO_ROOT = Path(__file__).resolve().parent.parent
WORKSPACE_ROOT = REPO_ROOT.parent
P65_DIR = REPO_ROOT / "research" / "phase6_5"
RESULTS_DIR = P65_DIR / "results"
PREDICTIONS_DIR = P65_DIR / "predictions"
CONFIGS_DIR = P65_DIR / "configs"
FIXTURES_DIR = P65_DIR / "fixtures"
GT_PATH = FIXTURES_DIR / "ground_truth.npy"
REPORT_PATH = WORKSPACE_ROOT / "phase6.5report.md"
LEDGER_PATH = P65_DIR / "ledger.jsonl"
PROGRESS_PATH = P65_DIR / "progress.json"

PANEL_MLP_NAMES = [
    "logan-fitzgerald",
    "william-graves",
    "raymond-barnes",
    "steven-rice",
    "sarah-kelley",
    "christopher-morales",
    "cheryl-graham",
    "renee-park",
]

FLOP_BUDGET = 2**41


def sha256_file(path: Path | str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(65536):
            h.update(chunk)
    return h.hexdigest()


def generate_wrapper_script(
    real_estimator_path: Path,
    wrapper_path: Path,
    offset: int,
    preds_save_path: Path,
) -> None:
    """Generate wrapper script. Prediction dumping is strictly registered in atexit."""
    wrapper_content = f'''"""Autogenerated Phase 6.5 evaluation wrapper."""
import atexit
import dataclasses
import os
import sys
from pathlib import Path
import numpy as np

from whestbench import BaseEstimator, SetupContext
from whestbench.domain import MLP
from whestbench.loader import load_estimator_from_path

_REAL_PATH = r"{real_estimator_path.resolve()}"
_OFFSET = {offset}
_PREDS_PATH = r"{preds_save_path.resolve()}"

_real_estimator, _ = load_estimator_from_path(_REAL_PATH)
_collected_preds = []

class Estimator(BaseEstimator):
    def setup(self, ctx: SetupContext) -> None:
        _real_estimator.setup(ctx)

    def predict(self, mlp: MLP, budget: int):
        if _OFFSET != 0:
            new_seed = int((mlp.seed + _OFFSET) & 0xFFFFFFFF)
            mlp = dataclasses.replace(mlp, seed=new_seed)
        pred = _real_estimator.predict(mlp, budget)
        # Fast reference capture: do not convert or serialize inside predict()!
        _collected_preds.append(pred)
        return pred

def _dump_captured_predictions():
    if _collected_preds:
        try:
            arrs = [np.asarray(p, dtype=np.float32) for p in _collected_preds]
            stacked = np.stack(arrs, axis=0)
            Path(_PREDS_PATH).parent.mkdir(parents=True, exist_ok=True)
            np.save(_PREDS_PATH, stacked)
        except Exception as e:
            sys.stderr.write(f"Warning: Failed to save captured predictions: {{e}}\\n")

atexit.register(_dump_captured_predictions)
'''
    wrapper_path.parent.mkdir(parents=True, exist_ok=True)
    with open(wrapper_path, "w", encoding="utf-8") as f:
        f.write(wrapper_content)


def load_ground_truth() -> np.ndarray:
    if not GT_PATH.exists():
        raise FileNotFoundError(f"Missing ground truth fixture: {GT_PATH}")
    return np.load(GT_PATH)  # (8, 16, 1024)


def compute_metrics(
    preds: np.ndarray,
    gt: np.ndarray,
    flops_per_mlp: List[int],
    residual_times: List[float],
) -> Dict[str, Any]:
    """Compute exact float64 metrics from captured predictions and billed FLOPs."""
    n_mlps = len(preds)
    gt_subset = gt[:n_mlps]

    # Layer 15 MSE per MLP
    raw_mses = []
    adj_scores = []
    utils = []
    per_mlp_metrics = []

    for i in range(n_mlps):
        pred_final = np.asarray(preds[i, -1], dtype=np.float64)
        gt_final = np.asarray(gt_subset[i, -1], dtype=np.float64)
        mse = float(np.mean((pred_final - gt_final) ** 2))
        raw_mses.append(mse)

        fl = flops_per_mlp[i]
        u = fl / FLOP_BUDGET
        utils.append(u)
        mult = max(0.10, u)
        score = mse * mult
        adj_scores.append(score)

        per_mlp_metrics.append({
            "mlp_order": i,
            "mlp_name": PANEL_MLP_NAMES[i] if i < len(PANEL_MLP_NAMES) else f"mlp_{i}",
            "final_layer_mse": mse,
            "flops_used": fl,
            "compute_utilization": u,
            "score_multiplier": mult,
            "adjusted_score": score,
            "residual_wall_time_s": residual_times[i] if i < len(residual_times) else 0.0,
        })

    mean_raw_mse = float(np.mean(raw_mses))
    mean_adj_score = float(np.mean(adj_scores))
    mean_util = float(np.mean(utils))
    max_residual = max(residual_times) if residual_times else 0.0

    return {
        "n_mlps": n_mlps,
        "mean_raw_final_mse": mean_raw_mse,
        "mean_adjusted_score": mean_adj_score,
        "mean_compute_utilization": mean_util,
        "max_residual_wall_time_s": max_residual,
        "per_mlp": per_mlp_metrics,
    }


def run_candidate_eval(
    candidate_path: str | Path,
    exp_id: str,
    n_mlps: int = 8,
    offset: int = 0,
    runner: str = "local",
    mode: str = "diagnostic",
    parent_sha256: str = "unknown",
    params: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    cand_path = Path(candidate_path).resolve()
    if not cand_path.exists():
        raise FileNotFoundError(f"Candidate file not found: {cand_path}")

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    PREDICTIONS_DIR.mkdir(parents=True, exist_ok=True)

    cand_sha = sha256_file(cand_path)
    ts_str = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    preds_file = PREDICTIONS_DIR / f"{exp_id}_{ts_str}_preds.npy"
    wrapper_file = P65_DIR / f".eval_wrapper_{exp_id}.py"

    generate_wrapper_script(cand_path, wrapper_file, offset, preds_file)

    print(f"\n[{exp_id}] Starting evaluation of {cand_path.name}")
    print(f"  SHA-256: {cand_sha[:16]}... | Mode: {mode} | Offset: {offset} | Runner: {runner}")

    cmd = [
        "uv", "run", "whest", "run",
        "--estimator", str(wrapper_file),
        "--dataset", str(WORKSPACE_ROOT / "datasets" / "mini"),
        "--split", "mini",
        "--n-mlps", str(n_mlps),
        "--runner", runner,
        "--format", "json",
    ]
    if mode == "diagnostic":
        cmd.append("--no-residual-wall-time-limit")

    hf_cache_dir = WORKSPACE_ROOT / ".cache" / "huggingface"
    hf_cache_dir.mkdir(parents=True, exist_ok=True)
    env = dict(os.environ)
    env["PYTHONUTF8"] = "1"
    env["HF_HOME"] = str(hf_cache_dir)
    env["HF_DATASETS_CACHE"] = str(hf_cache_dir / "datasets")

    start_t = datetime.datetime.now()
    proc = subprocess.run(cmd, capture_output=True, text=True, env=env, cwd=str(REPO_ROOT))
    elapsed_s = (datetime.datetime.now() - start_t).total_seconds()

    if wrapper_file.exists():
        try:
            wrapper_file.unlink()
        except Exception:
            pass

    # Parse stdout JSON
    stdout = proc.stdout
    json_start = stdout.find("{")

    if json_start == -1:
        if proc.returncode != 0:
            print(f"[{exp_id}] whest run FAILED with code {proc.returncode}!")
            print("STDERR:")
            print(proc.stderr[:1000])
            return {"status": "FAILED", "returncode": proc.returncode, "stderr": proc.stderr}
        print(f"[{exp_id}] No JSON found in whest run stdout!")
        return {"status": "FAILED_NO_JSON", "stdout": stdout[:1000]}

    try:
        raw_json = json.loads(stdout[json_start:])
    except Exception as e:
        print(f"[{exp_id}] Failed to parse JSON: {e}")
        return {"status": "FAILED_JSON_PARSE", "error": str(e), "stdout": stdout[:1000]}

    raw_json_path = RESULTS_DIR / f"{exp_id}_{ts_str}.json"
    with open(raw_json_path, "w", encoding="utf-8") as f:
        json.dump(raw_json, f, indent=2)

    # Extract official runner results
    results_block = raw_json.get("results", {})
    if not results_block and not raw_json.get("ok", True):
        print(f"[{exp_id}] whest run returned error: {raw_json.get('error')}")
        return {"status": "FAILED", "error": raw_json.get("error")}

    official_failures = results_block.get("n_failed_mlps", 0)
    official_adj_score = results_block.get("adjusted_final_layer_score", None)
    per_mlp_whest = results_block.get("per_mlp", [])
    flops_per_mlp = [m.get("flops_used", 0) for m in per_mlp_whest]
    residual_times = [m.get("residual_wall_time_s", 0.0) for m in per_mlp_whest]

    # Check captured predictions or reconstruct from runner results
    if preds_file.exists() and preds_file.stat().st_size > 0:
        captured_preds = np.load(preds_file)
        gt = load_ground_truth()
        captured_metrics = compute_metrics(captured_preds, gt, flops_per_mlp, residual_times)
    elif per_mlp_whest:
        print(f"[{exp_id}] Note: Reconstructing captured metrics directly from official runner results.")
        per_mlp_metrics = []
        raw_mses = []
        adj_scores = []
        utils = []
        for i, m in enumerate(per_mlp_whest):
            mse = float(m.get("final_layer_mse", 0.0))
            fl = int(m.get("flops_used", 0))
            u = float(m.get("compute_utilization", fl / FLOP_BUDGET))
            mult = max(0.10, u)
            score = float(m.get("adjusted_final_layer_score", mse * mult))
            res_t = float(m.get("residual_wall_time_s", 0.0))
            raw_mses.append(mse)
            adj_scores.append(score)
            utils.append(u)
            per_mlp_metrics.append({
                "mlp_order": i,
                "mlp_name": m.get("mlp_name", PANEL_MLP_NAMES[i] if i < len(PANEL_MLP_NAMES) else f"mlp_{i}"),
                "final_layer_mse": mse,
                "flops_used": fl,
                "compute_utilization": u,
                "score_multiplier": mult,
                "adjusted_score": score,
                "residual_wall_time_s": res_t,
            })
        captured_metrics = {
            "n_mlps": len(per_mlp_whest),
            "mean_raw_final_mse": float(np.mean(raw_mses)) if raw_mses else 0.0,
            "mean_adjusted_score": float(np.mean(adj_scores)) if adj_scores else 0.0,
            "mean_compute_utilization": float(np.mean(utils)) if utils else 0.0,
            "max_residual_wall_time_s": max(residual_times) if residual_times else 0.0,
            "per_mlp": per_mlp_metrics,
        }
    else:
        captured_metrics = None

    # Determine status
    max_res = max(residual_times) if residual_times else 0.0
    if mode == "diagnostic":
        status = "RESEARCH_ONLY"
    elif official_failures == 0 and max_res <= 0.40:
        status = "VALIDATED"
    else:
        status = "RESEARCH_ONLY"

    receipt = {
        "exp_id": exp_id,
        "timestamp_utc": datetime.datetime.utcnow().isoformat() + "Z",
        "candidate_file": str(cand_path),
        "candidate_sha256": cand_sha,
        "parent_sha256": parent_sha256,
        "parameters": params or {},
        "status": status,
        "evaluation_mode": mode,
        "runner": runner,
        "seed_offset": offset,
        "n_mlps": n_mlps,
        "elapsed_wall_time_s": elapsed_s,
        "official_runner": {
            "n_failed_mlps": official_failures,
            "adjusted_final_layer_score": official_adj_score,
            "mean_compute_utilization": results_block.get("mean_compute_utilization"),
            "failure_breakdown": results_block.get("failure_breakdown", {}),
        },
        "captured_metrics": captured_metrics,
        "raw_json_path": str(raw_json_path),
        "predictions_path": str(preds_file) if preds_file.exists() else None,
    }

    # Append to ledger.jsonl
    with open(LEDGER_PATH, "a", encoding="utf-8") as f:
        f.write(json.dumps(receipt) + "\n")

    # Update progress.json
    progress = {}
    if PROGRESS_PATH.exists():
        try:
            with open(PROGRESS_PATH, "r", encoding="utf-8") as f:
                progress = json.load(f)
        except Exception:
            pass
    progress["last_completed"] = exp_id
    progress["last_receipt_time"] = receipt["timestamp_utc"]
    with open(PROGRESS_PATH, "w", encoding="utf-8") as f:
        json.dump(progress, f, indent=2)

    # Summary print
    if captured_metrics:
        print(f"[{exp_id}] Evaluation Complete:")
        print(f"  Status:              {status}")
        print(f"  Raw Final MSE:       {captured_metrics['mean_raw_final_mse']:.6e}")
        print(f"  Compute Util:        {captured_metrics['mean_compute_utilization']*100:.2f}% (mult: {max(0.1, captured_metrics['mean_compute_utilization']):.4f})")
        print(f"  Projected Score:     {captured_metrics['mean_adjusted_score']:.6e}")
        print(f"  Max Residual Time:   {captured_metrics['max_residual_wall_time_s']:.4f}s")
        print(f"  Official Failures:   {official_failures}")

    return receipt


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--candidate", type=str, required=True, help="Candidate estimator file")
    parser.add_argument("--exp-id", type=str, required=True, help="Experiment ID")
    parser.add_argument("--n-mlps", type=int, default=8, help="Number of MLPs to evaluate")
    parser.add_argument("--offset", type=int, default=0, help="Sampler seed offset")
    parser.add_argument("--runner", type=str, default="local", choices=["local", "subprocess"])
    parser.add_argument("--mode", type=str, default="diagnostic", choices=["diagnostic", "unrelaxed"])
    args = parser.parse_args()

    run_candidate_eval(
        candidate_path=args.candidate,
        exp_id=args.exp_id,
        n_mlps=args.n_mlps,
        offset=args.offset,
        runner=args.runner,
        mode=args.mode,
    )
