FLOP_BUDGET = 2**41


def sha256_file(path: Path | str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(65536):
            h.update(chunk)
    return h.hexdigest()


def generate_wrapper_script(
    real_estimator_path: Path,
    wrapper_path: Path,
    offset: int,
    preds_save_path: Path,
) -> None:
    """Generate wrapper script. Predictions are saved both per-predict and stacked on exit."""
    wrapper_content = f'''"""Autogenerated Phase 8 evaluation wrapper."""
import atexit
import dataclasses
import os
import sys
from pathlib import Path
import numpy as np

from whestbench import BaseEstimator, SetupContext
from whestbench.domain import MLP
from whestbench.loader import load_estimator_from_path

_REAL_PATH = r"{real_estimator_path.resolve()}"
_OFFSET = {offset}
_PREDS_PATH = r"{preds_save_path.resolve()}"

_real_estimator, _ = load_estimator_from_path(_REAL_PATH)
_collected_preds = []

class Estimator(BaseEstimator):
    def setup(self, ctx: SetupContext) -> None:
        _real_estimator.setup(ctx)

    def predict(self, mlp: MLP, budget: int):
        if _OFFSET != 0:
            new_seed = int((mlp.seed + _OFFSET) & 0xFFFFFFFF)
            mlp = dataclasses.replace(mlp, seed=new_seed)
        pred = _real_estimator.predict(mlp, budget)
        arr = np.asarray(pred, dtype=np.float32)
        _collected_preds.append(arr)
        try:
            p_dir = Path(_PREDS_PATH).with_suffix("")
            p_dir.mkdir(parents=True, exist_ok=True)
            m_name = getattr(mlp, "name", f"mlp_{{len(_collected_preds)}}")
            np.save(p_dir / f"{{m_name}}.npy", arr)
        except Exception:
            pass
        return pred

def _dump_captured_predictions():
    if _collected_preds:
        try:
            stacked = np.stack(_collected_preds, axis=0)
            p_path = Path(_PREDS_PATH)
            p_path.parent.mkdir(parents=True, exist_ok=True)
            tmp_p = p_path.with_suffix(".tmp.npy")
            np.save(tmp_p, stacked)
            if tmp_p.exists():
                tmp_p.replace(p_path)
        except Exception as e:
            sys.stderr.write(f"Warning: Failed to save captured predictions: {{e}}\\n")

atexit.register(_dump_captured_predictions)
'''
    wrapper_path.parent.mkdir(parents=True, exist_ok=True)
    with open(wrapper_path, "w", encoding="utf-8") as f:
        f.write(wrapper_content)


def load_dev8_ground_truth() -> np.ndarray:
    if not GT_DEV8_PATH.exists():
        raise FileNotFoundError(f"Missing ground truth fixture: {GT_DEV8_PATH}")
    return np.load(GT_DEV8_PATH)  # (8, 16, 1024)


def compute_metrics(
    preds: np.ndarray,
    gt: np.ndarray,
    flops_per_mlp: List[int],
    residual_times: List[float],
    panel_names: List[str],
) -> Dict[str, Any]:
    n_mlps = len(preds)
    gt_subset = gt[:n_mlps]

    raw_mses = []
    adj_scores = []
    utils = []
    per_mlp_metrics = []

    for i in range(n_mlps):
        pred_final = np.asarray(preds[i, -1], dtype=np.float64)
        gt_final = np.asarray(gt_subset[i, -1], dtype=np.float64)
        mse = float(np.mean((pred_final - gt_final) ** 2))
        raw_mses.append(mse)

        fl = flops_per_mlp[i] if i < len(flops_per_mlp) else 0
        u = fl / FLOP_BUDGET
        utils.append(u)
        mult = max(0.10, u)
        score = mse * mult
        adj_scores.append(score)

        per_mlp_metrics.append({
            "mlp_order": i,
            "mlp_name": panel_names[i] if i < len(panel_names) else f"mlp_{i}",
            "final_layer_mse": mse,
            "flops_used": fl,
            "compute_utilization": u,
            "score_multiplier": mult,
            "adjusted_score": score,
            "residual_wall_time_s": residual_times[i] if i < len(residual_times) else 0.0,
        })

    return {
        "n_mlps": n_mlps,
        "mean_raw_final_mse": float(np.mean(raw_mses)),
        "mean_compute_utilization": float(np.mean(utils)),
        "mean_adjusted_score": float(np.mean(adj_scores)),
        "max_residual_wall_time_s": float(max(residual_times)) if residual_times else 0.0,
        "raw_final_mses": raw_mses,
        "adjusted_scores": adj_scores,
        "per_mlp": per_mlp_metrics,
    }


def compare_candidates(cand_receipt: Dict[str, Any], base_receipt: Dict[str, Any]) -> Dict[str, Any]:
    cand_scores = [m["adjusted_score"] for m in cand_receipt.get("captured_metrics", {}).get("per_mlp", [])]
    base_scores = [m["adjusted_score"] for m in base_receipt.get("captured_metrics", {}).get("per_mlp", [])]

    if not cand_scores or not base_scores or len(cand_scores) != len(base_scores):
        return {"wins": 0, "losses": 0, "ties": 0, "ratios": [], "mean_ratio": 1.0, "worst_ratio": 1.0}

    wins = sum(1 for c, b in zip(cand_scores, base_scores) if c < b)
    losses = sum(1 for c, b in zip(cand_scores, base_scores) if c > b)
    ties = sum(1 for c, b in zip(cand_scores, base_scores) if c == b)
    ratios = [c / max(b, 1e-15) for c, b in zip(cand_scores, base_scores)]

    return {
        "wins": wins,
        "losses": losses,
        "ties": ties,
        "ratios": ratios,
        "mean_ratio": float(np.mean(ratios)),
        "worst_ratio": float(max(ratios)),
    }


def run_paired_bootstrap(
    cand_scores: List[float],
    base_scores: List[float],
    n_resamples: int = 2000,
    seed: int = 8199,
) -> Dict[str, Any]:
    rng = np.random.default_rng(seed)
    n = len(cand_scores)
    diffs = np.array(cand_scores) - np.array(base_scores)
    ratios = np.array(cand_scores) / np.maximum(np.array(base_scores), 1e-15)

    mean_diffs = []
    mean_ratios = []
    for _ in range(n_resamples):
        idx = rng.integers(0, n, size=n)
        mean_diffs.append(float(np.mean(diffs[idx])))
        mean_ratios.append(float(np.mean(ratios[idx])))

    ci_diff_lower = float(np.percentile(mean_diffs, 2.5))
    ci_diff_upper = float(np.percentile(mean_diffs, 97.5))
    ci_ratio_lower = float(np.percentile(mean_ratios, 2.5))
    ci_ratio_upper = float(np.percentile(mean_ratios, 97.5))

    return {
        "n_resamples": n_resamples,
        "seed": seed,
        "mean_diff": float(np.mean(diffs)),
        "ci_diff_95": [ci_diff_lower, ci_diff_upper],
        "mean_ratio": float(np.mean(ratios)),
        "ci_ratio_95": [ci_ratio_lower, ci_ratio_upper],
    }


def get_latest_receipt(exp_id: str) -> Optional[Dict[str, Any]]:
    if not LEDGER_PATH.exists():
        return None
    latest = None
    with open(LEDGER_PATH, "r", encoding="utf-8") as f:
        for line in f:
            if not line.strip():
                continue
            try:
                rec = json.loads(line)
                if rec.get("exp_id") == exp_id:
                    latest = rec
            except Exception:
                pass
    return latest


def update_current_thing_p8(
    method_name: str,
    short_desc: str,
    raw_final_mse: float,
    mean_score_mult: float,
    adjusted_score: float,
    max_residual_time: float,
    failures: int,
    wins_vs_control7: str,
    decision: str,
) -> None:
    """Update Current thing.md with dedicated Phase 8 validation table."""
    if not CURRENT_THING_PATH.exists():
        return

    text = CURRENT_THING_PATH.read_text(encoding="utf-8")

    # Header for Phase 8 section if not present
    p8_header = "## Phase 8 (1024x16, Budget 2^41) Validation Results (Fixed 8-MLP Panel)"
    table_header = (
        f"{p8_header}\n\n"
        "| Method / Variant | Short Description | Raw Final MSE | Mean Score Mult | Adjusted Score | Max Residual Time | Failures | Wins vs CONTROL7 | Decision |\n"
        "|---|---|---|---|---|---|---|---|---|\n"
    )

    row = (
        f"| **{method_name}** | {short_desc} | **{raw_final_mse:.4e}** | "
        f"**{mean_score_mult:.4f} ({mean_score_mult*100:.2f}%)** | **{adjusted_score:.4e}** | "
        f"{max_residual_time:.4f}s | {failures} | **{wins_vs_control7}** | **{decision}** |\n"
    )

    if p8_header not in text:
        # Append section at the end
        new_text = text.rstrip() + "\n\n" + table_header + row
    else:
        # Check if row already exists
        lines = text.splitlines()
        found_p8 = False
        row_exists = False
        insert_idx = len(lines)
        for i, line in enumerate(lines):
            if p8_header in line:
                found_p8 = True
            elif found_p8 and line.startswith("## "):
                insert_idx = i
                break
            elif found_p8 and f"| **{method_name}** |" in line:
                lines[i] = row.strip()
                row_exists = True
                break

        if row_exists:
            new_text = "\n".join(lines) + "\n"
        else:
            lines.insert(insert_idx, row.strip())
            new_text = "\n".join(lines) + "\n"

    CURRENT_THING_PATH.write_text(new_text, encoding="utf-8")


def append_to_phase8report(receipt: Dict[str, Any], comp_c7: Dict[str, Any]) -> None:
    if not REPORT_PATH.exists():
        return

    exp_id = receipt["exp_id"]
    cand_sha = receipt["candidate_sha256"]
    mode = receipt["mode"]
    metrics = receipt["captured_metrics"]
    raw_mse = metrics["mean_raw_final_mse"]
    util = metrics["mean_compute_utilization"]
    score = metrics["mean_adjusted_score"]
    max_res = metrics["max_residual_wall_time_s"]
    fails = receipt["official_failures"]
    status = receipt["status"]

    report_entry = f"""
### Candidate `{exp_id}` Evaluation Receipt
- **Timestamp**: `{receipt['timestamp']}`
- **Candidate File**: `{receipt['candidate_file']}` (SHA: `{cand_sha[:16]}...`)
- **Runner Mode**: `{mode}` | **Status**: `{status}`
- **Dev-8 Performance**:
  - Raw Final MSE: `{raw_mse:.6e}`
  - Compute Utilization: `{util*100:.2f}%` (Score Multiplier: `{max(0.10, util):.4f}`)
  - **Adjusted Final Score**: `{score:.6e}`
  - Max Residual Time: `{max_res:.4f}s`
  - Official Failures: `{fails}`
- **Head-to-Head vs CONTROL7 (2.6337e-08)**:
  - Record: **{comp_c7['wins']}W - {comp_c7['losses']}L - {comp_c7['ties']}T**
  - Score Ratio (Cand / C7): Mean = `{comp_c7['mean_ratio']:.4f}`, Worst = `{comp_c7['worst_ratio']:.4f}`
  - Projected Improvement: `{(1.0 - comp_c7['mean_ratio'])*100:+.2f}%`
"""
    with open(REPORT_PATH, "a", encoding="utf-8") as f:
        f.write(report_entry)


def run_candidate_eval(
    candidate_path: Path | str,
    exp_id: str,
    n_mlps: int = 8,
    offset: int = 0,
    mode: str = "diagnostic",  # "diagnostic" (relaxed residual) or "unrelaxed" (0.4s cap)
    panel: str = "dev8",
    runner: str = "subprocess",
    parent_sha256: Optional[str] = None,
    params: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    cand_path = Path(candidate_path).resolve()
    if not cand_path.exists():
        raise FileNotFoundError(f"Candidate not found: {cand_path}")

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    PREDICTIONS_DIR.mkdir(parents=True, exist_ok=True)

    cand_sha = sha256_file(cand_path)
    ts_str = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")

    wrapper_file = REPO_ROOT / f"_tmp_wrapper_{exp_id}_{ts_str}.py"
    preds_file = PREDICTIONS_DIR / f"{exp_id}_{ts_str}_preds.npy"

    generate_wrapper_script(cand_path, wrapper_file, offset, preds_file)

    print(f"\n[{exp_id}] Starting evaluation of {cand_path.name}")
    print(f"  SHA-256: {cand_sha[:16]}... | Mode: {mode} | Offset: {offset} | Runner: {runner} | Panel: {panel}")

    eval_n_mlps = 20 if panel == "conf12" else n_mlps

    cmd = [
        "uv", "run", "whest", "run",
        "--estimator", str(wrapper_file),
        "--dataset", str(WORKSPACE_ROOT / "datasets" / "mini"),
        "--split", "mini",
        "--n-mlps", str(eval_n_mlps),
        "--runner", runner,
        "--wall-time-limit", "120.0",
        "--setup-timeout", "60.0",
        "--format", "json",
    ]
    if mode == "diagnostic":
        cmd.append("--no-residual-wall-time-limit")

    env = dict(os.environ)
    env["PYTHONUTF8"] = "1"
    hf_cache_dir = WORKSPACE_ROOT / ".cache" / "huggingface"
    hf_cache_dir.mkdir(parents=True, exist_ok=True)
    env["HF_HOME"] = str(hf_cache_dir)
    env["HF_DATASETS_CACHE"] = str(hf_cache_dir / "datasets")

    official_res = {}
    proc_out = ""
    proc_err = ""
    try:
        res_proc = subprocess.run(
            cmd,
            cwd=str(REPO_ROOT),
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            encoding="utf-8",
            errors="replace",
            env=env,
            check=False,
        )
        proc_out = res_proc.stdout
        proc_err = res_proc.stderr

        # Find JSON blob
        json_start = proc_out.find("{")
        json_end = proc_out.rfind("}")
        if json_start != -1 and json_end != -1:
            json_str = proc_out[json_start:json_end + 1]
            official_res = json.loads(json_str)
        else:
            print(f"Warning: JSON output not found in stdout. Stderr:\n{proc_err[:1000]}")
    finally:
        if wrapper_file.exists():
            try:
                wrapper_file.unlink()
            except Exception:
                pass

    # Save official JSON output
    out_json_path = RESULTS_DIR / f"{exp_id}_{ts_str}.json"
    with open(out_json_path, "w", encoding="utf-8") as f:
        json.dump(official_res, f, indent=2)

    # Extract official per-mlp compute metrics
    r = official_res.get("results", {})
    flops_per_mlp = [m.get("effective_compute", m.get("flops_used", 0)) for m in r.get("per_mlp", [])]
    residual_times = [m.get("residual_wall_time_s", 0.0) for m in r.get("per_mlp", [])]

    # Load captured predictions with fallback to official results
    metrics = None
    try:
        if preds_file.exists():
            captured_preds = np.load(preds_file)
            if captured_preds.ndim == 3 and captured_preds.shape[0] == n_mlps:
                print(f"  Captured predictions shape: {captured_preds.shape}")
                gt = load_dev8_ground_truth()
                metrics = compute_metrics(
                    captured_preds,
                    gt,
                    flops_per_mlp,
                    residual_times,
                    PANEL_DEV8_NAMES[:n_mlps],
                )
    except Exception as e:
        print(f"  Note: Captured predictions array could not be loaded ({e}); using official whest results.")

    if metrics is None:
        # Fall back directly to official runner results
        r = official_res.get("results", {})
        all_per_mlp = r.get("per_mlp", [])
        if panel == "conf12":
            selected_per_mlp = all_per_mlp[8:20]
        else:
            selected_per_mlp = all_per_mlp[:n_mlps]

        raw_mses = [m["final_layer_mse"] for m in selected_per_mlp]
        adj_scores = [m["adjusted_final_layer_score"] for m in selected_per_mlp]
        res_times = [m.get("residual_wall_time_s", 0.0) for m in selected_per_mlp]
        per_mlp_metrics = []
        for i, m in enumerate(selected_per_mlp):
            fl = m.get("flops_used", 0)
            u = m.get("effective_compute", fl) / FLOP_BUDGET
            per_mlp_metrics.append({
                "mlp_order": i,
                "mlp_name": m.get("mlp_name", f"mlp_{i}"),
                "final_layer_mse": m["final_layer_mse"],
                "flops_used": fl,
                "compute_utilization": u,
                "score_multiplier": max(0.10, u),
                "adjusted_score": m["adjusted_final_layer_score"],
                "residual_wall_time_s": m.get("residual_wall_time_s", 0.0),
            })
        utils = [m["compute_utilization"] for m in per_mlp_metrics]
        metrics = {
            "n_mlps": len(raw_mses),
            "mean_raw_final_mse": float(np.mean(raw_mses) if raw_mses else 0.0),
            "mean_compute_utilization": float(np.mean(utils) if utils else 0.0),
            "mean_adjusted_score": float(np.mean(adj_scores) if adj_scores else 0.0),
            "max_residual_wall_time_s": float(max(res_times)) if res_times else 0.0,
            "raw_final_mses": raw_mses,
            "adjusted_scores": adj_scores,
            "per_mlp": per_mlp_metrics,
        }

    official_fails = official_res.get("results", {}).get("n_failed_mlps", 0)
    status = "VALIDATED" if (official_fails == 0 and metrics["max_residual_wall_time_s"] <= 0.40) else "RESEARCH_ONLY"

    receipt = {
        "exp_id": exp_id,
        "timestamp": ts_str,
        "candidate_file": str(cand_path),
        "candidate_sha256": cand_sha,
        "parent_sha256": parent_sha256,
        "mode": mode,
        "offset": offset,
        "status": status,
        "panel": panel,
        "n_mlps": n_mlps,
        "official_failures": official_fails,
        "captured_metrics": metrics,
        "official_results_file": str(out_json_path),
        "predictions_file": str(preds_file),
        "params": params,
    }

    # Atomically update ledger and progress
    with open(LEDGER_PATH, "a", encoding="utf-8") as f:
        f.write(json.dumps(receipt) + "\n")

    progress = {}
    if PROGRESS_PATH.exists():
        with open(PROGRESS_PATH, "r", encoding="utf-8") as f:
            progress = json.load(f)
    progress.setdefault("completed_experiments", {})[exp_id] = {
        "timestamp": ts_str,
        "status": status,
        "mean_raw_final_mse": metrics["mean_raw_final_mse"],
        "mean_compute_utilization": metrics["mean_compute_utilization"],
        "mean_adjusted_score": metrics["mean_adjusted_score"],
        "candidate_sha256": cand_sha,
    }
    with open(PROGRESS_PATH, "w", encoding="utf-8") as f:
        json.dump(progress, f, indent=2)

    # Compare with CONTROL7
    base_id = "CONTROL7-CONF12" if panel == "conf12" else "CONTROL7"
    ctrl7_receipt = get_latest_receipt(base_id)
    comp_c7 = compare_candidates(receipt, ctrl7_receipt) if ctrl7_receipt else {"wins": 0, "losses": 0, "ties": 0, "mean_ratio": 1.0, "worst_ratio": 1.0}

    # Run paired bootstrap if both receipts available
    bootstrap_res = None
    if ctrl7_receipt and receipt.get("exp_id") != base_id:
        cand_scores = [m["adjusted_score"] for m in receipt["captured_metrics"]["per_mlp"]]
        base_scores = [m["adjusted_score"] for m in ctrl7_receipt["captured_metrics"]["per_mlp"]]
        if len(cand_scores) == len(base_scores) and len(cand_scores) > 0:
            bootstrap_res = run_paired_bootstrap(cand_scores, base_scores, n_resamples=2000, seed=8199)

    print(f"[{exp_id}] Results:")
    print(f"  Raw Final MSE: {metrics['mean_raw_final_mse']:.6e}")
    print(f"  Utilization:   {metrics['mean_compute_utilization']*100:.2f}% (Multiplier: {max(0.10, metrics['mean_compute_utilization']):.4f})")
    print(f"  Adjusted Score: {metrics['mean_adjusted_score']:.6e}")
    print(f"  Max Residual:  {metrics['max_residual_wall_time_s']:.4f}s")
    print(f"  Failures:      {official_fails}")
    print(f"  vs {base_id}:   {comp_c7['wins']}W - {comp_c7['losses']}L (Score Ratio: {comp_c7['mean_ratio']:.4f})")
    if bootstrap_res:
        print(f"  Bootstrap (2000 resamples): Mean Ratio: {bootstrap_res['mean_ratio']:.4f} (95% CI: [{bootstrap_res['ci_ratio_95'][0]:.4f}, {bootstrap_res['ci_ratio_95'][1]:.4f}])")
        print(f"                              Mean Diff:  {bootstrap_res['mean_diff']:.4e} (95% CI: [{bootstrap_res['ci_diff_95'][0]:.4e}, {bootstrap_res['ci_diff_95'][1]:.4e}])")

    # Update reports
    append_to_phase8report(receipt, comp_c7)

    desc = params.get("description", exp_id) if params else exp_id
    update_current_thing_p8(
        method_name=exp_id,
        short_desc=desc,
        raw_final_mse=metrics["mean_raw_final_mse"],
        mean_score_mult=max(0.10, metrics["mean_compute_utilization"]),
        adjusted_score=metrics["mean_adjusted_score"],
        max_residual_time=metrics["max_residual_wall_time_s"],
        failures=official_fails,
        wins_vs_control7=f"{comp_c7['wins']}W-{comp_c7['losses']}L vs {base_id}",
        decision="CONFIRMED" if (panel == "conf12" and comp_c7['wins'] >= 9) else ("QUALIFIED" if comp_c7['wins'] >= 6 and comp_c7['mean_ratio'] <= 0.80 else "EVALUATED"),
    )

    return receipt


