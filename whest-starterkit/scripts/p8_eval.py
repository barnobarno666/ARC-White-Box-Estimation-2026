"""p8_eval.py

Phase 8 Evaluation Harness and Verification Runner.
Supports:
1. Exact metered evaluation via official `whest run`.
2. Seed offset injection via wrapper without adding predict-time overhead.
3. Synchronous + atexit prediction capture to guarantee non-empty arrays.
4. Paired scoring against ground truth in float64.
5. Distinction between RESEARCH_ONLY (diagnostic with relaxed residual gate)
   and VALIDATED (unrelaxed runner passing official 0.4s cap).
6. Atomically updates research/phase8/ledger.jsonl, progress.json, and appends to phase8report.md.
7. Updates Current thing.md keeping Phase 8 validation table separate.
"""

