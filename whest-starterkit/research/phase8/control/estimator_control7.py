    m_pad = m + (m % 2)
    k_pad = k + (k % 2)
    p_pad = p + (p % 2)
    A_p = fnp.pad(A, ((0, m % 2), (0, k % 2))) if (m % 2 != 0 or k % 2 != 0) else A
    B_p = fnp.pad(B, ((0, k % 2), (0, p % 2))) if (k % 2 != 0 or p % 2 != 0) else B

    m2, k2_h, p2 = m_pad // 2, k_pad // 2, p_pad // 2
    A11, A12 = A_p[:m2, :k2_h], A_p[:m2, k2_h:]
    A21, A22 = A_p[m2:, :k2_h], A_p[m2:, k2_h:]
    B11, B12 = B_p[:k2_h, :p2], B_p[:k2_h, p2:]
    B21, B22 = B_p[k2_h:, :p2], B_p[k2_h:, p2:]

    M1 = (A11 + A22) @ (B11 + B22)
    M2 = (A21 + A22) @ B11
    M3 = A11 @ (B12 - B22)
    M4 = A22 @ (B21 - B11)
    M5 = (A11 + A12) @ B22
    M6 = (A21 - A11) @ (B11 + B12)
    M7 = (A12 - A22) @ (B21 + B22)

    C11 = M1 + M4 - M5 + M7
    C12 = M3 + M5
    C21 = M2 + M4
    C22 = M1 - M2 + M3 + M6

    top = fnp.concatenate([C11, C12], axis=1)
    bot = fnp.concatenate([C21, C22], axis=1)
    C_full = fnp.concatenate([top, bot], axis=0)
    return C_full[:m, :p]

